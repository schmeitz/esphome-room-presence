<#
.SYNOPSIS
  Copies the room-presence packages to the ESPHome config folder of Home Assistant,
  makes sure the shared secrets exist and (optionally) creates a device file for a room.

  Run without -RoomName to be asked for the room interactively.

.PARAMETER RoomName
  Free text. Becomes the Home Assistant area of the node (created when it does not exist yet).
.PARAMETER RoomId
  Hostname part (a-z, 0-9, '-'); derived from RoomName when omitted. Node hostname = room-<RoomId>.
.PARAMETER FriendlyName
  Device name shown in Home Assistant; default "Room <RoomName>".

.EXAMPLE
  .\tools\Deploy-ToHomeAssistant.ps1
  .\tools\Deploy-ToHomeAssistant.ps1 -RoomName "Living room"
  .\tools\Deploy-ToHomeAssistant.ps1 -EsphomeDir \\homeassistant.local\config\esphome -RoomName Office -RoomId office-1

.NOTES
  Works in Windows PowerShell 5.1. Writes YAML as UTF-8 without BOM with LF line endings.
#>
param(
  [string]$EsphomeDir = "\\homeassistant.local\config\esphome",
  [string]$RoomName,
  [string]$RoomId,
  [string]$FriendlyName,
  [string]$Board = "esp32dev",
  [switch]$PackagesOnly
)
$ErrorActionPreference = "Stop"
$repo = Split-Path $PSScriptRoot
$utf8 = New-Object System.Text.UTF8Encoding($false)

function Write-Lf([string]$Path, [string]$Text) {
  [IO.File]::WriteAllText($Path, ($Text -replace "`r`n", "`n"), $utf8)
}
function New-RandomString([int]$Bytes) {
  $b = New-Object byte[] $Bytes
  [Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($b)
  [Convert]::ToBase64String($b)
}

if (-not (Test-Path $EsphomeDir)) { throw "ESPHome folder not found: $EsphomeDir" }

# 1. Packages
$target = Join-Path $EsphomeDir "packages\room-presence"
New-Item -ItemType Directory -Force $target | Out-Null
Get-ChildItem (Join-Path $repo "packages") -Filter *.yaml | ForEach-Object {
  Write-Lf (Join-Path $target $_.Name) ([IO.File]::ReadAllText($_.FullName))
  Write-Host "package  -> $(Join-Path $target $_.Name)"
}

# 2. Shared secrets (only added when missing, existing values are never touched)
$secretsPath = Join-Path $EsphomeDir "secrets.yaml"
$secrets = if (Test-Path $secretsPath) { [IO.File]::ReadAllText($secretsPath) } else { "" }
$add = @()
$wanted = [ordered]@{
  room_node_api_key      = { New-RandomString 32 }
  room_node_ota_password = { (New-RandomString 24) -replace '[+/=]', '' }
  room_node_ap_password  = { (New-RandomString 12) -replace '[+/=]', '' }
  room_node_web_password = { (New-RandomString 12) -replace '[+/=]', '' }
}
foreach ($k in $wanted.Keys) {
  if ($secrets -notmatch "(?m)^$k\s*:") { $add += "${k}: `"$(& $wanted[$k])`"" ; Write-Host "secret   + $k (generated)" }
}
foreach ($k in "wifi_ssid", "wifi_password") {
  if ($secrets -notmatch "(?m)^$k\s*:") { Write-Warning "secrets.yaml has no '$k' - add it before compiling." }
}
if ($add.Count) {
  $block = "`n# esphome-room-presence (shared by all room nodes), added $(Get-Date -Format yyyy-MM-dd)`n" + ($add -join "`n") + "`n"
  if ($secrets -and -not $secrets.EndsWith("`n")) { $block = "`n" + $block }
  Write-Lf $secretsPath ($secrets + $block)
}

# 3. Device file for a room
if (-not $PackagesOnly -and -not $RoomName -and [Environment]::UserInteractive) {
  $RoomName = (Read-Host "In which room will this node be placed? (empty = skip)").Trim()
}
if (-not $PackagesOnly -and $RoomName) {
  if (-not $RoomId) {
    $norm = $RoomName.Normalize([Text.NormalizationForm]::FormD) -replace '\p{Mn}', ''
    $RoomId = ($norm.ToLowerInvariant() -replace '[^a-z0-9]+', '-').Trim('-')
  }
  if ($RoomId -notmatch '^[a-z0-9-]{1,24}$') { throw "RoomId may only contain a-z, 0-9 and '-' (max 24, it becomes the hostname)." }
  if (-not $FriendlyName) { $FriendlyName = "Room $RoomName" }
  $file = Join-Path $EsphomeDir "room-$RoomId.yaml"
  if (Test-Path $file) {
    Write-Host "device   = $file already exists, left unchanged"
  } else {
    $boardLine = if ($Board -ne "esp32dev") { "`n  board: $Board" } else { "" }
    Write-Lf $file @"
# Room node - generated by esphome-room-presence (https://github.com/schmeitz/esphome-room-presence)
substitutions:
  name: room-$RoomId
  friendly_name: "$($FriendlyName -replace '"', '')"
  room: "$($RoomName -replace '"', '')"$boardLine

packages:
  room_node: !include packages/room-presence/room-node.yaml

"@
    Write-Host "device   + $file"
  }
}
